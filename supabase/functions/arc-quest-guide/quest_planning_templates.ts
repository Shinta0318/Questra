export function resolveQuestPlanningTemplate(
  quest: QuestTemplateInput,
): QuestPlanningTemplate {
  const category = normalize(quest.category);
  const source = normalize(
    `${quest.category ?? ""} ${quest.title ?? ""} ${quest.description ?? ""}`,
  );
  const productSignals = [
    "flutter",
    "アプリ",
    "ポートフォリオ",
    "ポッドキャスト",
    "ニュースレター",
    "オンラインショップ",
    "サイトを公開",
  ];
  if (productSignals.some((value) => source.includes(normalize(value)))) {
    return questPlanningTemplates.find((template) => template.id === "product") ??
      generalTemplate;
  }
  const categoryMatch = questPlanningTemplates.find((template) =>
    template.categories.some((value) => category.includes(normalize(value)))
  );
  if (categoryMatch) return categoryMatch;
  return questPlanningTemplates.find((template) =>
    template.keywords.some((value) => source.includes(normalize(value)))
  ) ?? generalTemplate;
}

function normalize(value?: string) {
  return (value ?? "").trim().toLocaleLowerCase("ja-JP");
}
